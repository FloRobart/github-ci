import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import { TitleProblem, parseConventionalTitle } from '../core/conventional-title.mjs';

describe('parseConventionalTitle with a valid title', () => {
  it('reads a simple title', () => {
    const parsedTitle = parseConventionalTitle('fix: corriger le calcul du solde');

    assert.equal(parsedTitle.isValid, true);
    assert.equal(parsedTitle.type, 'fix');
    assert.equal(parsedTitle.scope, null);
    assert.equal(parsedTitle.isBreaking, false);
    assert.equal(parsedTitle.description, 'corriger le calcul du solde');
    assert.deepEqual(parsedTitle.problems, []);
  });

  it('reads the scope', () => {
    const parsedTitle = parseConventionalTitle('feat(auth): ajouter la connexion par e-mail');

    assert.equal(parsedTitle.isValid, true);
    assert.equal(parsedTitle.type, 'feat');
    assert.equal(parsedTitle.scope, 'auth');
  });

  it('reads the breaking change marker, with or without a scope', () => {
    assert.equal(parseConventionalTitle('feat!: changer le format des dates').isBreaking, true);
    assert.equal(parseConventionalTitle('feat(api)!: supprimer la route /v1/users').isBreaking, true);
  });

  it('accepts a description containing a colon', () => {
    const parsedTitle = parseConventionalTitle('docs: expliquer le format type: description');

    assert.equal(parsedTitle.isValid, true);
    assert.equal(parsedTitle.description, 'expliquer le format type: description');
  });

  it('accepts the titles generated by the pipeline', () => {
    assert.equal(parseConventionalTitle('chore(release): 1.4.0').isValid, true);
    assert.equal(parseConventionalTitle('chore(hotfix): 1.4.1').isValid, true);
    assert.equal(parseConventionalTitle('chore(release): back-merge v1.4.0 vers develop').isValid, true);
  });
});

describe('parseConventionalTitle with an invalid title', () => {
  it('reports a missing separator', () => {
    const parsedTitle = parseConventionalTitle('Ajout de la connexion');

    assert.equal(parsedTitle.isValid, false);
    assert.deepEqual(parsedTitle.problems, [TitleProblem.MISSING_SEPARATOR]);
  });

  it('reports a malformed header', () => {
    assert.deepEqual(parseConventionalTitle('Update README: typo').problems, [TitleProblem.MALFORMED_HEADER]);
    assert.deepEqual(parseConventionalTitle('feat (auth): login').problems, [TitleProblem.MALFORMED_HEADER]);
    assert.deepEqual(parseConventionalTitle(': login').problems, [TitleProblem.MALFORMED_HEADER]);
  });

  it('reports an unknown type', () => {
    assert.deepEqual(parseConventionalTitle('feature: login').problems, [TitleProblem.UNKNOWN_TYPE]);
  });

  it('reports a type written with capital letters', () => {
    assert.deepEqual(parseConventionalTitle('Feat: login').problems, [TitleProblem.UNKNOWN_TYPE]);
  });

  it('reports an empty scope', () => {
    assert.deepEqual(parseConventionalTitle('feat(): login').problems, [TitleProblem.EMPTY_SCOPE]);
  });

  it('reports an empty description', () => {
    assert.deepEqual(parseConventionalTitle('feat:').problems, [TitleProblem.EMPTY_DESCRIPTION]);
    assert.deepEqual(parseConventionalTitle('feat:   ').problems, [TitleProblem.EMPTY_DESCRIPTION]);
  });

  it('reports a missing space after the separator', () => {
    assert.deepEqual(parseConventionalTitle('feat:login').problems, [TitleProblem.MISSING_SPACE_AFTER_SEPARATOR]);
  });

  it('reports every problem at once', () => {
    assert.deepEqual(parseConventionalTitle('feature():login').problems, [
      TitleProblem.UNKNOWN_TYPE,
      TitleProblem.EMPTY_SCOPE,
      TitleProblem.MISSING_SPACE_AFTER_SEPARATOR,
    ]);
  });
});

describe('parseConventionalTitle with custom types', () => {
  it('only accepts the given types', () => {
    assert.equal(parseConventionalTitle('deps: mettre à jour express', ['deps']).isValid, true);
    assert.equal(parseConventionalTitle('feat: login', ['deps']).isValid, false);
  });
});
